import type { Item, Priority, Workspace } from "./types";
const updated = "2026-10-29T16:00:00Z";
const entry = (
  value: Pick<Item, "id" | "kind" | "title"> & Partial<Item>,
): Item => ({
  subtitle: "",
  year: "",
  cover_url: null,
  source: null,
  external_id: null,
  position: 0,
  completed_at: null,
  created_at: updated,
  list_id: null,
  tags: [],
  priority: "normal",
  ...value,
});
const tmdb = (
  id: string,
  kind: "movie" | "series",
  title: string,
  year: string,
  subtitle: string,
  externalId: number,
  poster: string,
  tags: string[],
) =>
  entry({
    id,
    kind,
    title,
    year,
    subtitle,
    source: "tmdb",
    external_id: String(externalId),
    cover_url: `https://image.tmdb.org/t/p/w342${poster}`,
    tags,
  });
const reading = (
  id: string,
  kind: "book" | "comic",
  title: string,
  subtitle: string,
  year: string,
  work: string,
  cover: number,
  tags: string[],
) =>
  entry({
    id,
    kind,
    title,
    subtitle,
    year,
    source: "openlibrary",
    external_id: work,
    cover_url: `https://covers.openlibrary.org/b/id/${cover}-M.jpg`,
    tags,
  });
const game = (
  id: string,
  title: string,
  subtitle: string,
  year: string,
  app: number,
  tags: string[],
) =>
  entry({
    id,
    kind: "game",
    title,
    subtitle,
    year,
    source: "steam",
    external_id: String(app),
    cover_url: `https://cdn.akamai.steamstatic.com/steam/apps/${app}/library_600x900.jpg`,
    tags,
  });
const task = (
  id: string,
  title: string,
  subtitle: string,
  list: string,
  priority: Priority,
  tags: string[],
  done = false,
) =>
  entry({
    id,
    kind: "task",
    title,
    subtitle,
    list_id: list,
    priority,
    tags,
    completed_at: done ? "2026-10-28T18:30:00Z" : null,
  });
